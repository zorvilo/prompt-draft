import assert from "node:assert/strict";
import { createServer } from "vite";
import { createSSRApp, h } from "vue";
import { renderToString } from "vue/server-renderer";
import { setup } from "@css-render/vue3-ssr";

const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: "custom" });
try {
  const { default: Panel } = await server.ssrLoadModule("/src/features/workspace/PromptWorkspace.vue");
  const source = { id: "d", source: "原始需求", result: "当前正文", title: "测试", messages: [], favorite: false };
  const render = async (draft, request) => { const app = createSSRApp({ render: () => h(Panel, { draft, request, templateName: "基础优化", contextUsage: { characters: 32000, messages: 25, ratio: 0.27, exceeded: false } }) }); setup(app); return renderToString(app); };

  const plain = await render({ ...source, dialogue: { mode: "draft",  } });
  assert.ok(plain.includes("draft-comparison-panels"));
  assert.ok(!plain.includes("尚未采用的新稿"));
  assert.ok(plain.includes("当前正文"));
  assert.ok(!plain.includes("版本历史"));
  assert.ok(!plain.includes("查看生成结果"));
  assert.ok(!plain.includes("采用此稿"));
  assert.ok(!plain.includes("本轮修改要求"));
  assert.ok(plain.includes("确认优化"));
  assert.ok(!plain.includes("modification-chat"));
  assert.ok(!plain.includes("聊天消息导航"));
  const messages = [{ id: "u", role: "user", content: "内部请求正文", displayContent: "先讨论", created: 1, context: { mode: "draft", templateName: "基础优化" }, model: "测试模型" }, { id: "a", role: "assistant", content: "只讨论，不生成稿件", created: 1, durationMs: 1234 }];
  const chat = await render({ ...source, messages, dialogue: { mode: "chat" } });
  assert.ok(chat.includes("已重新优化，后续对话从这里开始"));
  assert.ok(chat.includes("chat-event-notice"));
  assert.ok(chat.includes("应用上下文用量 27%，32000 字符，25 条消息"));
  assert.ok(chat.includes("用时 1.2 秒"));
  assert.ok(chat.includes("下载回复"));
  assert.ok(!chat.includes("用作优化稿"));
  assert.ok(!chat.includes("删除回复"));
  assert.ok(chat.includes("复制消息"));
  assert.ok(chat.includes("conversation-user-actions"));
  assert.ok(chat.includes("<time"));
  assert.ok(chat.includes("放大查看回复"));
  assert.ok(chat.includes("chat-send-button"));
  assert.ok(chat.includes("modification-chat"));
  assert.ok(chat.includes("聊天消息导航"));
  assert.ok(chat.includes("跳转到第 1 次提问：先讨论"));
  assert.ok(!chat.includes("跳转到第 2 次提问"));
  const more = await render({ ...source, messages: [...messages, { id: "u2", role: "user", content: "第二次提问", created: 2 }, { id: "a2", role: "assistant", content: "第二次回答", created: 3 }], dialogue: { mode: "chat" } });
  assert.ok(more.includes("跳转到第 2 次提问：第二次提问"));
  assert.ok(!more.includes("跳转到第 3 次提问"));

  assert.ok(chat.includes("先讨论"));
  assert.ok(chat.includes("只讨论，不生成稿件"));
  assert.ok(!chat.includes("内部请求正文"));
  assert.ok(!chat.includes("采用此稿"), "discussion replies have no adoption action");
  const ordinaryChat = await render({ ...source, messages: [{ ...messages[0], context: { mode: "chat" } }, messages[1]], dialogue: { mode: "chat" } });
  assert.ok(!ordinaryChat.includes("用作优化稿"));
  const busy = await render({ ...source, dialogue: { mode: "chat", chatInput: "下一条消息" } }, { text: "", userMessage: "刚刚发送的消息" });
  const switched = await render({ ...source, messages: [...messages.slice(0, 1), { ...messages[1], model: "旧模型", providerName: "旧供应商" }], dialogue: { mode: "chat" } }, { text: "", userMessage: "切换后提问", mode: "chat", model: "新模型", providerName: "新供应商" });
  assert.ok(switched.includes("已切换至 新供应商 · 新模型"));
  assert.ok(switched.includes("chat-event-notice"));
  assert.ok(busy.includes("停止生成"));
  assert.ok(busy.includes("词稿正在回复"));
  assert.ok(busy.includes("刚刚发送的消息"));
  assert.ok(busy.includes("下一条消息"));
  assert.ok(!/<textarea[^>]*\sdisabled/.test(busy), "composer stays editable during generation");
  const streaming = await render({ ...source, dialogue: { mode: "chat",  } }, { text: '正在输出正文', userMessage: "继续修改" });
  assert.ok(streaming.includes("正在输出正文"));
  assert.ok(!streaming.includes("已更新提示词"));
  const plainStream = await render({ ...source, dialogue: { mode: "chat",  } }, { text: "普通聊天也逐步显示", userMessage: "先聊一下" });
  assert.ok(plainStream.includes("普通聊天也逐步显示"));
  const jsonReply = '{"content":"保留 JSON 示例"}';
  const jsonStream = await render({ ...source, dialogue: { mode: "chat",  } }, { text: jsonReply, userMessage: "写一个 JSON 示例" });
  assert.ok(jsonStream.includes("保留 JSON 示例"));
  assert.ok(jsonStream.includes("content"), "JSON examples must not be stripped as protocol envelopes");
  const { default: Navigation } = await server.ssrLoadModule("/src/features/workspace/ChatNavigation.vue");
  const navApp = createSSRApp({ render: () => h(Navigation, { messages: [...messages, { id: "u2", role: "user", content: "第二个提问", created: 2 }], visibleIds: ["u", "u2"] }) });
  setup(navApp);
  const navHtml = await renderToString(navApp);
  assert.equal((navHtml.match(/class="chat-navigation-tick is-visible"/g) ?? []).length, 2);
  assert.ok(!navHtml.includes("is-active"));
  console.log("prompt workspace rendering, pending results, discussion and loading states passed");
} finally {
  await server.close();
}
