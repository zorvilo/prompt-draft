import { contextTokenBudget } from "../src/utils/workspace/contextBudget.ts";
import assert from "node:assert/strict";
import { prepareConversation, currentResultReply, conversationUsage, recordReply, changeMode, latestContext } from "../src/utils/workspace/conversation.ts";
import { duplicateDraft } from "../src/utils/workspace/duplicateDraft.ts";
const template = { id: "basic", name: "基础优化", content: "保留原意", userContent: "需求：{{{draftContent}}}" };
const draft = { id: "d", title: "稿", source: "面向新手", result: "", messages: [], favorite: false };
const reply = (conversation, content, mode) => recordReply(draft, conversation, { content }, mode, "model", "供应商", 1234);
const first = prepareConversation(draft, template, undefined, "draft");
reply(first, "第一稿", "draft");
assert.equal(draft.result, "第一稿");
assert.equal(draft.source, "面向新手");
assert.equal(draft.messages.length, 2);
assert.equal(draft.messages[0].context.mode, "draft");
assert.equal(draft.messages[0].context.currentDraft, "第一稿");
assert.equal(draft.messages[1].model, "model");
assert.equal(draft.messages[1].durationMs, 1234);
changeMode(draft, "chat");
draft.dialogue.chatInput = "下一条尚未发送";
const before = JSON.stringify(draft);
const discussion = prepareConversation(draft, { ...template, content: "新模板" }, "先分析，不改稿", "chat");
assert.equal(JSON.stringify(draft), before);
assert.equal(discussion.systemPrompt, first.systemPrompt);
assert.deepEqual(discussion.messages.slice(0, 2).map(message => message.content), ["需求：面向新手", "第一稿"]);
const switched = prepareConversation(draft, { ...template, id: "professional", name: "专业优化", content: "专业规则" }, "换种方式", "chat");
assert.ok(switched.systemPrompt.includes("专业规则"));
assert.equal(latestContext(draft).templateId, "basic");
reply(discussion, "建议简化结构", "chat");
const modification = prepareConversation(draft, template, "按建议修改", "chat");
assert.ok(modification.messages.some(message => message.content === "建议简化结构"));
reply(modification, "聊天中修改的新稿", "chat");
assert.equal(draft.result, "聊天中修改的新稿");
assert.equal(latestContext(draft).currentDraft, draft.result);
assert.equal(draft.messages.length, 6);
changeMode(draft, "draft");
const isolated = prepareConversation(draft, template, undefined, "draft");
assert.equal(isolated.messages.length, 1);
assert.equal(isolated.messages[0].content, "需求：面向新手");
reply(isolated, "第二次独立优化", "draft");
assert.equal(draft.messages.length, 8, "reoptimization preserves all earlier records");
assert.equal(draft.result, "第二次独立优化");
changeMode(draft, "chat");
const next = prepareConversation(draft, template, "继续精简", "chat");
assert.deepEqual(next.messages.map(message => message.content), ["需求：面向新手", "第二次独立优化", "继续精简"]);
assert.equal(draft.dialogue.chatInput, "下一条尚未发送");
const restored = prepareConversation({ ...draft, result: "第一稿" }, template, "继续精简", "chat");
assert.equal(restored.messages[1].content, "第二次独立优化");
assert.ok(restored.messages.at(-1).content.includes('"currentDraft":"第一稿"'));
draft.result = "手动编辑";
assert.ok(prepareConversation(draft, template, "继续", "chat").messages.at(-1).content.includes("手动编辑"));
reply(isolated, "最新结果", "draft");
assert.equal(draft.result, "最新结果");
assert.equal(draft.source, "面向新手");
assert.ok(draft.messages.some(message => message.content === "第一稿"));
assert.equal(duplicateDraft(draft).messages.length, 0);
assert.equal(duplicateDraft(draft).dialogue, undefined);
const empty = { ...draft, source: "最初需求", result: "", messages: [], dialogue: { mode: "chat" } };
const initial = prepareConversation(empty, template, undefined, "chat");
recordReply(empty, initial, { content: "先讨论一下" }, "chat", "model", "供应商");
assert.equal(empty.result, "先讨论一下");
assert.equal(empty.messages.length, 2);
assert.equal(prepareConversation(empty, template, "继续", "chat").messages.length, 3);
const copy = { ...empty, messages: [], result: "复制来的正文" };
const seeded = prepareConversation(copy, template, "修改第二段", "chat");
recordReply(copy, seeded, { content: "可以这样调整" }, "chat", "model", "供应商");
assert.equal(copy.messages.length, 4);
assert.equal(prepareConversation(copy, template, "继续", "chat").messages.length, 5);
assert.throws(() => prepareConversation({ ...draft, result: "长".repeat(60001) }, template, "改", "chat"), /60,000/);
assert.throws(() => prepareConversation(draft, template, "改".repeat(4001), "chat"), /4,000/);
console.log("unified message history, fresh optimization context, chat continuity and latest result passed");

const incomplete = structuredClone(draft);
incomplete.messages.pop();
const continued = prepareConversation(incomplete, template, "继续讨论", "chat");
assert.ok(!continued.messages.some(message => message.content === "最新结果"));
assert.equal(continued.messages.at(-1).role, "user");
console.log("incomplete saved turns do not break subsequent requests");

const timed = { ...empty, messages: [] };
const beforeCompletion = Date.now();
const actualSendTime = beforeCompletion - 5000;
recordReply(timed, prepareConversation(timed, template, undefined, "chat"), { content: "回复" }, "chat", "model", "供应商", 5000, actualSendTime);
assert.equal(timed.messages[0].created, actualSendTime);
assert.ok(timed.messages[1].created >= beforeCompletion);
assert.ok(timed.messages[1].created - timed.messages[0].created >= 5000);
console.log("user send time and assistant completion time are saved independently");

assert.equal(conversationUsage({ messages: [] }).tokens, undefined);
assert.equal(conversationUsage({ messages: [{ role: "assistant", inputTokens: 80000 }] }).ratio, 80000 / contextTokenBudget);
assert.equal(conversationUsage({ messages: [{ role: "assistant", inputTokens: contextTokenBudget }] }).exceeded, true);
assert.equal(conversationUsage({ messages: [{ role: "assistant", inputTokens: 240000 }] }).ratio, 240000 / contextTokenBudget);
assert.equal(conversationUsage({ messages: [{ role: "assistant", inputTokens: 80000 }, { role: "assistant" }] }).tokens, undefined);
const longHistory = { ...draft, messages: Array.from({ length: 110 }, (_, i) => ({ id: String(i), role: i % 2 ? "assistant" : "user", content: "正文" })) };
assert.ok(prepareConversation(longHistory, template, "继续", "chat").messages.length > 99);

const resultMessages = [
  { id: "template", role: "assistant", content: "第一稿" },
  { id: "chat", role: "assistant", content: "改进稿" },
];
assert.equal(currentResultReply({ result: "改进稿", messages: resultMessages }).id, "chat");
assert.equal(currentResultReply({ result: "第一稿", messages: resultMessages }).id, "template");
assert.equal(currentResultReply({ result: "手动修改稿", messages: resultMessages }), undefined);
assert.equal(currentResultReply({ result: "", messages: resultMessages }), undefined);
assert.equal(currentResultReply({ result: "改进稿", messages: [...resultMessages, { id: "latest", role: "assistant", content: "改进稿" }] }).id, "latest");

const metered = { ...draft, messages: [] };
recordReply(metered, prepareConversation(metered, template, undefined, "draft"), { content: "回复", inputTokens: 200000 }, "draft", "model", "provider");
assert.equal(metered.messages.at(-1).inputTokens, 200000);
assert.equal(conversationUsage(metered).exceeded, true);
